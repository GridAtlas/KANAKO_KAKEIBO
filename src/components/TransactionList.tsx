"use client";

import Link from "next/link";
import { Pencil, X } from "lucide-react";
import { useBudgetStore } from "@/store/useBudgetStore";
import { getIcon } from "@/lib/icons";
import { formatYen } from "@/lib/money";
import { formatDateShort } from "@/lib/date";
import type { Transaction } from "@/types";

interface Props {
  items: Transaction[];
  emptyText?: string;
  editHref?: (id: string) => string;
  compact?: boolean;
}

export function TransactionList({ items, emptyText, editHref, compact }: Props) {
  const getCategoryById = useBudgetStore((s) => s.getCategoryById);
  const removeTransaction = useBudgetStore((s) => s.removeTransaction);

  if (items.length === 0) {
    return (
      <div className={`rounded-2xl border border-[var(--line)] bg-[var(--surface)] text-center text-sm text-[var(--muted)] ${compact ? "p-4" : "p-6"}`}>
        {emptyText ?? "まだ取引がありません"}
      </div>
    );
  }

  return (
    <div className="divide-y divide-[var(--line)] overflow-hidden rounded-2xl border border-[var(--line)] bg-[var(--surface)] shadow-[0_6px_18px_rgba(96,45,57,0.05)]">
      {items.map((t) => {
        const cat = getCategoryById(t.categoryId);
        const Icon = getIcon(cat?.icon ?? "HelpCircle");
        const color = cat?.color ?? "slate";
        const isIncome = cat?.type === "income";
        const contentClass = `flex min-w-0 flex-1 items-center ${compact ? "gap-2" : "gap-3"}`;
        const content = (
          <>
            <div
              className={`flex shrink-0 items-center justify-center rounded-full ring-1 ring-inset ring-black/5 ${compact ? "size-8" : "size-10"} bg-${color}-100 text-${color}-700`}
            >
              <Icon size={compact ? 16 : 20} aria-hidden="true" />
            </div>
            <div className="flex-1 min-w-0">
              <div className="flex items-baseline gap-2">
                <span className={`truncate font-semibold text-[var(--ink)] ${compact ? "text-sm" : ""}`}>
                  {cat?.name ?? "削除済カテゴリ"}
                </span>
                {t.isAutoGenerated && (
                  <span className="shrink-0 rounded bg-[#f8edd9] px-1 text-[10px] font-semibold text-[#7c552d]">
                    固定費
                  </span>
                )}
              </div>
              <div className="truncate text-xs text-[var(--muted)]">
                {formatDateShort(t.date)}
                {t.memo ? ` · ${t.memo}` : ""}
              </div>
            </div>
            <div
              className={`font-bold tabular-nums ${compact ? "max-w-[45%] break-all text-right text-sm leading-4" : ""} ${
                isIncome ? "text-[var(--sage)]" : "text-[var(--ink)]"
              }`}
            >
              {isIncome ? "+" : ""}
              {formatYen(t.amount)}
            </div>
          </>
        );
        return (
          <div key={t.id} className={`flex items-center ${compact ? "gap-1 px-2 py-0.5" : "gap-2 px-3 py-2.5"}`}>
            {editHref ? (
              <Link href={editHref(t.id)} className={`${contentClass} min-h-11 rounded-lg hover:bg-[#fbebef]`}>
                {content}
                <Pencil size={14} className="shrink-0 text-[var(--accent)]" aria-hidden="true" />
                <span className="sr-only">を編集</span>
              </Link>
            ) : (
              <div className={contentClass}>{content}</div>
            )}
            <button
              type="button"
              className="tap-target -mr-1 p-1 text-[var(--muted)] hover:text-[var(--accent)]"
              aria-label="削除"
              onClick={() => {
                if (confirm("この取引を削除しますか？")) {
                  removeTransaction(t.id);
                }
              }}
            >
              <X size={16} />
            </button>
          </div>
        );
      })}
    </div>
  );
}
