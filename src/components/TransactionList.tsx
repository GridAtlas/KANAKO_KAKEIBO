"use client";

import { X } from "lucide-react";
import { useBudgetStore } from "@/store/useBudgetStore";
import { getIcon } from "@/lib/icons";
import { formatYen } from "@/lib/money";
import { formatDateShort } from "@/lib/date";
import type { Transaction } from "@/types";

interface Props {
  items: Transaction[];
  emptyText?: string;
  onItemClick?: (t: Transaction) => void;
  compact?: boolean;
}

export function TransactionList({ items, emptyText, onItemClick, compact }: Props) {
  const getCategoryById = useBudgetStore((s) => s.getCategoryById);
  const removeTransaction = useBudgetStore((s) => s.removeTransaction);

  if (items.length === 0) {
    return (
      <div className={`rounded-2xl border text-center text-sm text-stone-500 ${compact ? "border-[#eadccf] bg-[#fffdf9] p-4" : "border-pink-100 bg-white/90 p-6"}`}>
        {emptyText ?? "まだ取引がありません"}
      </div>
    );
  }

  return (
    <div className={`overflow-hidden rounded-2xl border divide-y ${compact ? "border-[#eadccf] bg-[#fffdf9] divide-[#f0e5db]" : "border-pink-100 bg-white/90 divide-pink-50"}`}>
      {items.map((t) => {
        const cat = getCategoryById(t.categoryId);
        const Icon = getIcon(cat?.icon ?? "HelpCircle");
        const color = cat?.color ?? "slate";
        const isIncome = cat?.type === "income";
        return (
          <div
            key={t.id}
            className={`flex items-center ${compact ? "gap-2 px-2 py-0.5" : "gap-3 px-3 py-2.5"}`}
            onClick={() => onItemClick?.(t)}
          >
            <div
              className={`flex shrink-0 items-center justify-center rounded-full ${compact ? "h-8 w-8" : "h-10 w-10"} bg-${color}-100 text-${color}-700`}
            >
              <Icon size={compact ? 16 : 20} aria-hidden="true" />
            </div>
            <div className="flex-1 min-w-0">
              <div className="flex items-baseline gap-2">
                <span className={`truncate font-semibold ${compact ? "text-sm" : ""}`}>
                  {cat?.name ?? "削除済カテゴリ"}
                </span>
                {t.isAutoGenerated && (
                  <span className="shrink-0 rounded bg-amber-100 px-1 text-[10px] text-amber-700">
                    固定費
                  </span>
                )}
              </div>
              <div className="text-xs text-stone-500 truncate">
                {formatDateShort(t.date)}
                {t.memo ? ` · ${t.memo}` : ""}
              </div>
            </div>
            <div
              className={`num font-bold ${compact ? "max-w-[45%] break-all text-right text-sm leading-4" : ""} ${
                isIncome ? "text-emerald-600" : "text-stone-900"
              }`}
            >
              {isIncome ? "+" : ""}
              {formatYen(t.amount)}
            </div>
            <button
              type="button"
              className="tap-target -mr-1 p-1 text-stone-400 hover:text-rose-600"
              aria-label="削除"
              onClick={(e) => {
                e.stopPropagation();
                if (confirm("この取引を削除しますか？")) {
                  removeTransaction(t.id);
                }
              }}
            >
              <X size={16} />
            </button>
          </div>
        );
      })}
    </div>
  );
}
