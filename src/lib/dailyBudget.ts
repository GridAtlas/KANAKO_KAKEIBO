import type { Category, Transaction } from "@/types";
import { dateToLocalString, daysInMonth } from "./date";

export interface DailyBudgetGoal {
  effectiveFrom: string;
  amount: number;
}

export interface DailyBudgetDay {
  date: string;
  amount: number;
  goal: number | null;
  status: "future" | "unconfigured" | "pending" | "achieved" | "over";
}

const miniKanakoStages = [-2, -1, 0, 1, 2] as const;
export type MiniKanakoStage = (typeof miniKanakoStages)[number];

export function getDailySpending(
  transactions: readonly Transaction[],
  categories: readonly Category[],
): Map<string, number> {
  const categoriesById = new Map(categories.map((category) => [category.id, category]));
  const spending = new Map<string, number>();

  for (const transaction of transactions) {
    const category = categoriesById.get(transaction.categoryId);
    if (transaction.isAutoGenerated || category?.isFixedCost || category?.type === "income") {
      continue;
    }
    spending.set(transaction.date, (spending.get(transaction.date) ?? 0) + transaction.amount);
  }

  return spending;
}

function goalAmountOnDate(date: string, goals: readonly DailyBudgetGoal[]): number | null {
  for (let index = goals.length - 1; index >= 0; index--) {
    const goal = goals[index];
    if (goal.effectiveFrom <= date) return goal.amount;
  }
  return null;
}

export function getDailyBudgetStatus(
  date: string,
  today: string,
  goals: readonly DailyBudgetGoal[],
  spending: ReadonlyMap<string, number>,
): DailyBudgetDay {
  const amount = spending.get(date) ?? 0;
  const goal = goalAmountOnDate(date, goals);
  let status: DailyBudgetDay["status"];

  if (date > today) status = "future";
  else if (goal === null) status = "unconfigured";
  else if (amount > goal) status = "over";
  else if (date === today) status = "pending";
  else status = "achieved";

  return { date, amount, goal, status };
}

export function getDailyBudgetMonth(
  monthKey: string,
  today: string,
  goals: readonly DailyBudgetGoal[],
  spending: ReadonlyMap<string, number>,
): DailyBudgetDay[] {
  return Array.from({ length: daysInMonth(monthKey) }, (_, index) => {
    const day = String(index + 1).padStart(2, "0");
    return getDailyBudgetStatus(`${monthKey}-${day}`, today, goals, spending);
  });
}

export function* getCompletedDailyBudgetOutcomes(
  today: string,
  goals: readonly DailyBudgetGoal[],
  spending: ReadonlyMap<string, number>,
): Generator<{ date: string; outcome: "achieved" | "over" }> {
  const start = goals[0]?.effectiveFrom;
  if (!start || start >= today) return;

  // 日付をローカル時刻で進め、夏時間で一日が 24 時間にならない地域にも対応する。
  const [year, month, day] = start.split("-").map(Number);
  const cursor = new Date(year, month - 1, day, 12);
  let goalIndex = 0;

  for (let date = start; date < today; date = dateToLocalString(cursor)) {
    while (goals[goalIndex + 1] && goals[goalIndex + 1].effectiveFrom <= date) goalIndex++;

    const amount = spending.get(date) ?? 0;
    yield { date, outcome: amount > goals[goalIndex].amount ? "over" : "achieved" };
    cursor.setDate(cursor.getDate() + 1);
  }
}

export function getMiniKanakoStage(
  today: string,
  goals: readonly DailyBudgetGoal[],
  spending: ReadonlyMap<string, number>,
): MiniKanakoStage {
  let stageIndex = 2;

  for (const { outcome } of getCompletedDailyBudgetOutcomes(today, goals, spending)) {
    if (outcome === "over") {
      stageIndex = Math.max(0, stageIndex - 1);
    } else {
      stageIndex = Math.min(miniKanakoStages.length - 1, stageIndex + 1);
    }
  }

  if (getDailyBudgetStatus(today, today, goals, spending).status === "over") {
    stageIndex = Math.max(0, stageIndex - 1);
  }

  return miniKanakoStages[stageIndex];
}
